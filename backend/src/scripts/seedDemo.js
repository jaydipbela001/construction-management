// Optional demo data seed. Safe to re-run: it only creates data if empty.
// Usage: node src/scripts/seedDemo.js
require('../config/loadEnv')();
const mongoose = require('mongoose');
const connectDB = require('../config/db');
const Project = require('../models/Project');
const Material = require('../models/Material');
const Expense = require('../models/Expense');

async function run() {
  await connectDB();

  const existing = await Project.countDocuments();
  if (existing > 0) {
    console.log('Projects already exist. Skipping demo seed to avoid mixing demo data.');
    await mongoose.connection.close();
    return process.exit(0);
  }

  const house = await Project.create({
    name: 'Residential House',
    projectCode: 'PRJ-HOUSE01',
    description: 'A two-storey independent residential house.',
    location: '12 Maple Street, Springfield',
    startDate: new Date('2026-01-10'),
    expectedCompletionDate: new Date('2026-09-30'),
    status: 'active',
    notes: 'Demo project generated by seed script.',
  });

  const commercial = await Project.create({
    name: 'Commercial Building',
    projectCode: 'PRJ-COMM02',
    description: 'A five-floor commercial office building.',
    location: '88 Market Avenue, Metropolis',
    startDate: new Date('2026-02-01'),
    expectedCompletionDate: new Date('2027-03-15'),
    status: 'planned',
  });

  await Material.insertMany([
    { projectId: house._id, name: 'Iron', category: 'Metal', quantity: 500, unit: 'kg', unitPrice: 65, supplier: 'MetalCo' },
    { projectId: house._id, name: 'Cement', category: 'Binding', quantity: 100, unit: 'bag', unitPrice: 380, supplier: 'BuildMart' },
    { projectId: house._id, name: 'Wood', category: 'Timber', quantity: 20, unit: 'unit', unitPrice: 1200 },
    { projectId: commercial._id, name: 'Sand', category: 'Aggregate', quantity: 10, unit: 'ton', unitPrice: 1500 },
    { projectId: commercial._id, name: 'Cement', category: 'Binding', quantity: 200, unit: 'bag', unitPrice: 390 },
    { projectId: commercial._id, name: 'Bricks', category: 'Masonry', quantity: 5000, unit: 'piece', unitPrice: 8 },
  ]);

  await Expense.insertMany([
    { projectId: house._id, title: 'Foundation labor', category: 'labor', amount: 45000, paymentMethod: 'bank_transfer', payee: 'ABC Contractors' },
    { projectId: commercial._id, title: 'Site permit fee', category: 'permits', amount: 120000, paymentMethod: 'cheque', payee: 'City Council' },
  ]);

  console.log('Demo data seeded.');
  await mongoose.connection.close();
  process.exit(0);
}

run().catch((err) => {
  console.error('Seed failed:', err.message);
  process.exit(1);
});
